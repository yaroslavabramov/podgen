"""Ported legacy ingestion health helpers."""

import re
from dataclasses import dataclass

from .cleaning import _normalize_whitespace
from .patterns import (
    _ACCESS_FORM_MARKERS,
    _ACCESS_ROUTE_MARKERS,
    _BOT_CHECK_RE,
    _CLOUDFRONT_REQUEST_ID_RE,
    _COOKIE_CONTROL_PHRASES,
    _COOKIE_UI_TOKENS,
    _HTTP_403_ERROR_RE,
    _HTTP_ERROR_BANNER_RE,
    _HTTP_ERROR_MAX_CHARS,
    _INVALID_URL_ERROR_RE,
    _JAVASCRIPT_CHALLENGE_RE,
    _MAINTENANCE_RE,
    _MISSING_DOCUMENT_RE,
    _NOT_FOUND_REQUEST_RE,
    _PREVIEW_ONLY_RE,
    _PUBLISHER_DOCUMENT_CONTROL_MARKERS,
    _PUBLISHER_SHELL_MAX_CHARS,
    _SECURITY_SERVICE_RE,
    _SERVICE_PAGE_MAX_CHARS,
    _TARGET_ACCESS_DENIAL_RE,
)


@dataclass(slots=True)
class WebQualityAssessment:
    state: str
    reasons: list[str]
    char_count: int
    non_whitespace_chars: int


def assess_web_fetch_health(text: str, *, min_chars: int) -> WebQualityAssessment:
    """Classify web extraction signal quality for Gate A."""
    normalized = _normalize_whitespace(text)
    blocked_reasons = _blocked_reasons(normalized)
    non_ws_chars = len(re.sub(r"\s+", "", text))
    raw_chars = len(text)

    if blocked_reasons:
        return WebQualityAssessment(
            state="blocked",
            reasons=blocked_reasons,
            char_count=len(normalized),
            non_whitespace_chars=non_ws_chars,
        )

    low_signal_reasons: list[str] = []
    if not normalized:
        low_signal_reasons.append("empty_text")
    if len(normalized) < min_chars:
        low_signal_reasons.append("too_short")
    if raw_chars >= 1000 and raw_chars > 0 and (non_ws_chars / raw_chars) < 0.2:
        low_signal_reasons.append("high_whitespace_ratio")

    state = "low_signal" if low_signal_reasons else "ok"
    return WebQualityAssessment(
        state=state,
        reasons=list(dict.fromkeys(low_signal_reasons)),
        char_count=len(normalized),
        non_whitespace_chars=non_ws_chars,
    )


def contains_blocking_signal(text: str) -> bool:
    normalized = _normalize_whitespace(text)
    return bool(_blocked_reasons(normalized))


def _blocked_reasons(normalized_text: str) -> list[str]:
    normalized_lower = normalized_text.lower()
    reasons: list[str] = []
    short_service_page = len(normalized_text) <= _SERVICE_PAGE_MAX_CHARS

    if short_service_page and _HTTP_ERROR_BANNER_RE.search(normalized_text):
        reasons.append("http_error_banner")
    if short_service_page and _INVALID_URL_ERROR_RE.search(normalized_text):
        reasons.append("invalid_url_error_page")

    # Require service-page structure rather than a single phrase that can
    # legitimately occur in an article discussing access failures.
    verification_markers = sum(
        marker in normalized_lower
        for marker in (
            "just a moment",
            "security verification",
            "checking your browser",
            "verify you are human",
        )
    )
    if short_service_page and verification_markers >= 2:
        reasons.append("verification_wall")
    if short_service_page and _BOT_CHECK_RE.search(normalized_text):
        reasons.append("bot_check")
    if (
        short_service_page
        and "captcha" in normalized_lower
        and (verification_markers or "403" in normalized_lower or "challenge" in normalized_lower)
    ):
        reasons.append("captcha_detected")
    if short_service_page and _JAVASCRIPT_CHALLENGE_RE.search(normalized_text):
        reasons.append("javascript_challenge")
    if short_service_page and _SECURITY_SERVICE_RE.search(normalized_text):
        reasons.append("security_service_block")
    if short_service_page and _MAINTENANCE_RE.search(normalized_text):
        reasons.append("maintenance_page")

    cloudfront_markers = (
        "request could not be satisfied" in normalized_lower,
        "generated by cloudfront" in normalized_lower,
        bool(_CLOUDFRONT_REQUEST_ID_RE.search(normalized_text)),
    )
    if short_service_page and sum(cloudfront_markers) >= 2:
        reasons.append("cloudfront_error_page")

    access_markers = sum(
        marker in normalized_lower
        for marker in (
            "access denied",
            "request blocked",
            "request could not be satisfied",
            "we can't connect to the server",
        )
    )
    if short_service_page and access_markers >= 2:
        reasons.append("access_denied")

    service_denial_markers = sum(
        marker in normalized_lower
        for marker in (
            "cannot be processed at this time",
            "contact the site administrator",
            "include reference number",
        )
    )
    if short_service_page and service_denial_markers >= 2:
        reasons.append("service_denial_page")

    access_form_markers = sum(marker in normalized_lower for marker in _ACCESS_FORM_MARKERS)
    if short_service_page and "password" in normalized_lower and access_form_markers >= 2:
        reasons.append("access_form_only")

    # A publisher shell can be longer than a generic error page because it
    # contains navigation, bibliographic metadata, an abstract, and purchase
    # controls. Require both an explicit target-content denial/preview signal
    # and an access route so an article discussing access restrictions is not
    # misclassified.
    access_route_markers = sum(marker in normalized_lower for marker in _ACCESS_ROUTE_MARKERS)
    document_control_markers = sum(
        marker in normalized_lower for marker in _PUBLISHER_DOCUMENT_CONTROL_MARKERS
    )
    publisher_shell = len(normalized_text) <= _PUBLISHER_SHELL_MAX_CHARS
    access_shell_structure = access_route_markers >= 2 or document_control_markers >= 2
    if (
        publisher_shell
        and _TARGET_ACCESS_DENIAL_RE.search(normalized_text)
        and access_route_markers
        and access_shell_structure
    ):
        reasons.append("target_content_access_restricted")
    if (
        publisher_shell
        and _PREVIEW_ONLY_RE.search(normalized_text)
        and access_route_markers
        and access_shell_structure
    ):
        reasons.append("target_content_preview_only")

    cookie_controls = sum(marker in normalized_lower for marker in _COOKIE_CONTROL_PHRASES)
    words = re.findall(r"[^\W_]+", normalized_lower, re.UNICODE)
    cookie_token_density = sum(word in _COOKIE_UI_TOKENS for word in words) / len(words) if words else 0.0
    cookie_lexical_diversity = len(set(words)) / len(words) if words else 0.0
    cookie_ui_only = len(normalized_text) <= 1200 or cookie_lexical_diversity <= 0.12
    if cookie_ui_only and cookie_controls >= 3 and cookie_token_density >= 0.25:
        reasons.append("cookie_consent_only")

    if short_service_page and (
        _MISSING_DOCUMENT_RE.search(normalized_text) or _NOT_FOUND_REQUEST_RE.search(normalized_text)
    ):
        reasons.append("document_not_found")

    # Handle HTTP 403 banners conservatively: short error pages only.
    if len(normalized_text) <= _HTTP_ERROR_MAX_CHARS and _HTTP_403_ERROR_RE.search(normalized_lower):
        reasons.append("http_403_error")

    return list(dict.fromkeys(reasons))
