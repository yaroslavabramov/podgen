@pytest.mark.asyncio
async def test_jina_is_separate_original_and_promoted_pdf_keeps_lineage(repo, scope, producer, monkeypatch):
    from podgen.sources.acquisition.fallbacks import jina_request
    from podgen.sources.extraction import pdf

    request, profile = setup(repo, scope, producer, enable_jina=True, min_text_chars=10)
    monkeypatch.setenv("JINA_API_KEY", "fake-key")
    jina_url, _ = jina_request(request.url, profile)
    portal = (
        "Title: Publisher\n###### Topics\n###### Countries\n###### Series\n"
        + "\n".join(f"[Navigation {i}](https://example.com/nav/{i})" for i in range(40))
        + "\n[Download PDF](https://example.com/paper.pdf)"
    )
    fetcher = Fetcher(
        {
            request.url: document("403 Forbidden", status=403),
            jina_url: document(portal, url=jina_url, content_type="text/markdown"),
            "https://example.com/paper.pdf": document(
                simple_pdf(), url="https://example.com/paper.pdf", content_type="application/pdf"
            ),
        }
    )
    monkeypatch.setattr(
        pdf,
        "_run_marker_with_hard_timeout",
        lambda *args: (_ for _ in ()).throw(RuntimeError("marker unavailable")),
    )
    result = await service.acquire_source(repo, scope[0], request, fetcher=fetcher)
    assert [source.role for source in result.sources] == ["original", "jina", "promoted_pdf"]
    assert len({source.source_revision_ref.artifact_id for source in result.sources}) == 3
    assert result.sources[0].status == "unavailable"
    assert "searchable original text" in contents(repo, scope[0], result.sources[-1].representation_refs[0])
    raw = repo.get(scope[0], result.sources[1].source_revision_ref).payload
    assert raw["requested_uri"] == jina_url
    assert raw["source_metadata_evidence"][0]["reported_url"] == request.url
    assert len(fetcher.calls) == 3


