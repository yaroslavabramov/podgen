@pytest.mark.asyncio
async def test_resume_after_original_save_does_not_fetch_again(repo, scope, producer):
    request, _ = setup(repo, scope, producer)
    fetcher = Fetcher()

    class Interrupted(BaseException):
        pass

    class Crash:
        async def extract(self, doc, profile, *, role):
            store = AcquisitionStore(repo, scope[0], request.operation_id)
            saved = store.get(role + ":original")
            assert (
                repo.read_runtime_blob(
                    scope[0], store.ref(role + ":original"), BlobRef.model_validate(saved["original_blob"])
                )
                == doc.body
            )
            raise Interrupted()

    with pytest.raises(Interrupted):
        await service.acquire_source(repo, scope[0], request, fetcher=fetcher, extractors=Crash())
    result = await service.acquire_source(repo, scope[0], request, fetcher=fetcher)
    assert result.status == "available" and len(fetcher.calls) == 1


