def contents(repo, project, ref):
    payload = repo.get(project, ref).payload
    return repo.read_blob(project, ref, BlobRef.model_validate(payload["canonical_text_blob"])).decode()


@pytest.mark.asyncio
async def test_exact_saved_original_full_representation_and_replay(repo, scope, producer):
    request, _ = setup(repo, scope, producer)
    raw = (
        "<html><head><title>Exact saved title</title></head><body><article><p>"
        + ARTICLE
        + "</p></article></body></html>"
    )
    fetcher = Fetcher({request.url: document(raw, content_type="text/html; charset=utf-8")})
    result = await service.acquire_source(repo, scope[0], request, fetcher=fetcher)
    assert result.status == "available" and len(result.sources) == 1, result.model_dump(mode="json")
    source = result.sources[0]
    revision = repo.get(scope[0], source.source_revision_ref).payload
    assert revision["title"] == "Exact saved title"
    assert (
        repo.read_blob(
            scope[0], source.source_revision_ref, BlobRef.model_validate(revision["original_blob"])
        )
        == raw.encode()
    )
    representation = repo.get(scope[0], source.representation_refs[0]).payload
    text = contents(repo, scope[0], source.representation_refs[0])
    assert "operating mechanism" in text
    assert representation["source_revision_ref"] == source.source_revision_ref.model_dump(mode="json")
    for block in representation["blocks"]:
        first, last = block["text_range"]
        assert text[first:last] and last <= len(text)
        assert block["original_anchor"]["basis"] == "extracted_text_only_no_verified_dom_or_pdf_anchor"
    assert await service.acquire_source(repo, scope[0], request, fetcher=fetcher) == result
    assert len(fetcher.calls) == 1
    assert AcquisitionResult.model_validate(result.model_dump(mode="json")) == result


