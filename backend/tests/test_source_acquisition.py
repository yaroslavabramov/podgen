@pytest.mark.asyncio
async def test_explicit_local_reprocess_after_extraction_failure_never_refetches(
    repo, scope, producer, monkeypatch
):
    from uuid import uuid4

    from podgen.sources.acquisition.contracts import ReExtractionRequest
    from podgen.sources.acquisition.reprocess import reprocess_source

    request, _ = setup(repo, scope, producer)
    fetcher = Fetcher()

    class BrokenExtractor:
        async def extract(self, *args, **kwargs):
            raise RuntimeError("Missing extractor dependency")

    result = await service.acquire_source(
        repo, scope[0], request, fetcher=fetcher, extractors=BrokenExtractor()
    )
    assert result.sources[0].status == "extraction_failed"
    assert await service.acquire_source(repo, scope[0], request, fetcher=fetcher) == result

    def forbidden(*args, **kwargs):
        pytest.fail("local re-extraction must not depend on DNS or network")

    monkeypatch.setattr(service, "_check_ssrf", forbidden)
    reprocess_request = ReExtractionRequest(
        operation_id=uuid4(),
        source_revision_ref=result.sources[0].source_revision_ref,
        profile_ref=request.profile_ref,
        reason="Install missing local extractor",
    )
    new = await reprocess_source(repo, scope[0], reprocess_request)
    assert new.status == "available" and len(fetcher.calls) == 1
    assert contents(repo, scope[0], new.sources[0].representation_refs[0]) == ARTICLE
    assert new.sources[0].source_revision_ref == result.sources[0].source_revision_ref
    assert await reprocess_source(repo, scope[0], reprocess_request) == new


