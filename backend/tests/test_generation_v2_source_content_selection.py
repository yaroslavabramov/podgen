def _assessment(state: str, *reasons: str) -> dict[str, object]:
    return {
        "schema_version": CONTENT_ASSESSMENT_SCHEMA_VERSION,
        "state": state,
        "reasons": list(reasons),
        "surface": "rendered_snapshot",
        "char_count": 500,
        "non_whitespace_chars": 420,
    }


def _source(project_id: uuid.UUID | None = None) -> Source:
    return Source(
        id=uuid.uuid4(),
        project_id=project_id or uuid.uuid4(),
        source_type=SourceType.WEB,
        original_url="https://example.com/report",
        ingestion_status=IngestionStatus.COMPLETED,
        is_temporary=False,
    )


def _version(
    source: Source,
    *,
    state: str | None = CONTENT_STATE_CONFIRMED,
    path: str | None = "versions/report.txt",
    kind: SourceRepresentationKind = SourceRepresentationKind.RENDERED_SNAPSHOT,
) -> SourceVersion:
    metadata = {} if state is None else {"content_assessment": _assessment(state)}
    return SourceVersion(
        id=uuid.uuid4(),
        source_id=source.id,
        project_id=source.project_id,
        kind=kind,
        storage_path=path,
        content_hash=uuid.uuid4().hex,
        metadata_=metadata,
        status=V2RecordStatus.READY,
        upload_status=V2RecordStatus.PENDING,
        is_active=True,
    )


def test_model_eligibility_requires_explicitly_available_stored_content() -> None:
    source = _source()
    confirmed = _version(source, state=CONTENT_STATE_CONFIRMED)
    unavailable = _version(source, state=CONTENT_STATE_UNAVAILABLE)
    unconfirmed = _version(source, state=CONTENT_STATE_UNCONFIRMED)
    url_only = _version(
        source,
        state=CONTENT_STATE_CONFIRMED,
        path=source.original_url,
        kind=SourceRepresentationKind.ORIGINAL_URL,
    )

    assert source_version_model_eligible(confirmed) is True
    assert source_version_content_state(unavailable) == CONTENT_STATE_UNAVAILABLE
    assert source_version_model_eligible(unavailable) is False
    assert source_version_model_eligible(unconfirmed) is False
    assert source_version_model_eligible(url_only) is False


def test_legacy_preflight_is_read_only_and_rejects_only_service_surfaces() -> None:
    source = _source()
    cookie = _version(source, state=None, path="legacy/cookie.txt")
    cloudfront = _version(source, state=None, path="legacy/cloudfront.txt")
    not_found = _version(source, state=None, path="legacy/not-found.txt")
    article = _version(source, state=None, path="legacy/article.txt")
    article_403 = _version(source, state=None, path="legacy/article-403.txt")
    article_403.metadata_ = {"status_code": 403}
    versions = [cookie, cloudfront, not_found, article, article_403]
    texts = {
        "legacy/cookie.txt": (
            "Cookie settings. Accept only necessary cookies. Accept all cookies. "
            "Manage your cookie preferences."
        ),
        "legacy/cloudfront.txt": (
            "403 ERROR. The request could not be satisfied. Generated by cloudfront. "
            "Request ID: tzWL_P-TH7fqtwA8sLlcagavIdcXnDKe4FJWyy5USftLf7eqq2bKZw=="
        ),
        "legacy/not-found.txt": (
            "300 Multiple Choices. The document name you requested could not be found on this server."
        ),
        "legacy/article.txt": (
            "This public report explains the history, operating mechanism, evidence, consequences, and limits. " * 20
        ),
        "legacy/article-403.txt": (
            "The archived report documents the policy history, causal mechanism, supporting evidence, and limits. " * 20
        ),
    }
    before = [(version.status, version.is_active, dict(version.metadata_ or {})) for version in versions]

    rejections = assess_run_content_rejections(
        [source],
        versions,
        storage_client=object(),
        download_text_fn=lambda _client, path: texts[path],
    )

    assert set(rejections) == {str(cookie.id), str(cloudfront.id), str(not_found.id)}
    assert "cookie_consent_only" in rejections[str(cookie.id)]
    assert "cloudfront_error_page" in rejections[str(cloudfront.id)]
    assert "document_not_found" in rejections[str(not_found.id)]
    assert str(article.id) not in rejections
    assert str(article_403.id) not in rejections
    assert [(version.status, version.is_active, dict(version.metadata_ or {})) for version in versions] == before


def test_selection_keeps_valid_source_when_another_source_has_unavailable_content(
    monkeypatch: pytest.MonkeyPatch,
) -> None:
    project_id = uuid.uuid4()
    invalid_source = _source(project_id)
    valid_source = _source(project_id)
    invalid_version = _version(invalid_source, state=CONTENT_STATE_UNAVAILABLE)
    valid_version = _version(valid_source, state=CONTENT_STATE_CONFIRMED)
    monkeypatch.setattr(source_corpus_selection, "_provider_uploads_required", lambda: False)

    usable_sources, usable_versions, provider_files, skipped, canonical_ids = (
        source_corpus_selection.select_ready_run_corpus(
            [invalid_source, valid_source],
            [invalid_version, valid_version],
            [],
            None,
            content_rejections={str(invalid_version.id): ["cookie_consent_only"]},
        )
    )

    assert usable_sources == [valid_source]
    assert usable_versions == [valid_version]
    assert provider_files == []
    assert canonical_ids == [str(valid_version.id)]
    assert skipped == [
        {
            "source_id": str(invalid_source.id),
            "reason": "target_content_unavailable",
            "source_type": str(invalid_source.source_type),
            "reason_codes": ["cookie_consent_only"],
        }
    ]


@pytest.mark.asyncio
async def test_provider_metadata_and_upload_reject_explicitly_unavailable_content() -> None:
    source = _source()
    version = _version(source, state=CONTENT_STATE_UNAVAILABLE)
    provider_index = ProviderCorpusIndex(
        id=uuid.uuid4(),
        project_id=source.project_id,
        provider="openai",
        provider_vector_store_id="vs-ready",
        scope="project",
        status=V2RecordStatus.READY,
        config={},
    )
    attributes = provider_attributes(version)
    provider_file = ProviderCorpusFile(
        id=uuid.uuid4(),
        provider_index_id=provider_index.id,
        source_id=source.id,
        source_version_id=version.id,
        provider="openai",
        provider_file_id="file-existing",
        status=V2RecordStatus.READY,
        attributes=attributes,
    )

    assert attributes["content_state"] == CONTENT_STATE_UNAVAILABLE
    assert attributes["content_confirmed"] is False
    assert version_uploadable(version) is False
    assert provider_file_search_ready(provider_file) is False

    def unexpected(*_args, **_kwargs):  # pragma: no cover - defensive
        raise AssertionError("unavailable content must not reach provider code")

    async def unexpected_async(*_args, **_kwargs):  # pragma: no cover - defensive
        raise AssertionError("unavailable content must not reach provider code")

    class Db:
        async def execute(self, _statement):  # pragma: no cover - defensive
            raise AssertionError("unavailable content must be rejected before DB provider state")

    deps = SourceCorpusProviderUploadDeps(
        get_openai_client=unexpected,
        version_upload_payload=unexpected,
        sync_provider_file_attributes=unexpected_async,
        ensure_vector_store_file_attached=unexpected_async,
        poll_provider_file_until_terminal=unexpected_async,
    )

    with pytest.raises(RuntimeError, match="content is not confirmed"):
        await ensure_provider_file(
            Db(),  # type: ignore[arg-type]
            None,
            provider_index,
            version,
            deps=deps,
        )


@pytest.mark.asyncio
async def test_retroclassification_preserves_immutable_status_but_deactivates_version() -> None:
    source = _source()
    existing = _version(source, state=None, path="legacy/shell.txt")

    class Result:
        def scalar_one_or_none(self):
            return existing

    class Db:
        added: list[object] = []
        flushes = 0

        async def execute(self, _statement):
            return Result()

        def add(self, item):  # pragma: no cover - defensive
            self.added.append(item)

        async def flush(self):
            self.flushes += 1

    db = Db()
    returned = await ensure_source_version(
        db,  # type: ignore[arg-type]
        source,
        kind=existing.kind,
        storage_path=existing.storage_path,
        content_hash=existing.content_hash,
        metadata={"content_assessment": _assessment(CONTENT_STATE_UNAVAILABLE, "cookie_consent_only")},
        status=V2RecordStatus.FAILED,
    )

    assert returned is existing
    assert existing.status == V2RecordStatus.READY
    assert existing.is_active is False
    assert existing.metadata_["content_assessment"]["state"] == CONTENT_STATE_UNAVAILABLE
    assert db.added == []
    assert db.flushes == 1
