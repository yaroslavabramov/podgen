def test_source_version_helpers_preserve_legacy_ready_compatibility() -> None:
    legacy = SimpleNamespace(
        status="ready",
        kind="rendered_snapshot",
        storage_path="snapshot.txt",
        metadata_={},
    )
    rejected = SimpleNamespace(
        status="failed",
        kind="rendered_snapshot",
        storage_path="blocked.txt",
        metadata_={
            "content_assessment": {
                "schema_version": CONTENT_ASSESSMENT_SCHEMA_VERSION,
                "state": CONTENT_STATE_UNAVAILABLE,
                "reasons": ["http_status_403"],
            }
        },
    )

    assert source_version_content_state(legacy) == CONTENT_STATE_CONFIRMED
    assert source_version_content_confirmed(legacy) is True
    assert source_version_model_eligible(legacy) is True
    assert source_version_content_state(rejected) == CONTENT_STATE_UNAVAILABLE
    assert source_version_content_confirmed(rejected) is False
    assert source_version_model_eligible(rejected) is False


