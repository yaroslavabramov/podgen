def _url_read_deps(calls: dict[str, list]) -> OpenAIUrlReadVersionDeps:
    async def ensure_version(_db, _source, **kwargs):
        calls["versions"].append(kwargs)
        return SimpleNamespace(id=uuid.uuid4(), **kwargs)

    def upload_text(_client, document, object_name):
        calls["uploads"].append((document, object_name))

    return OpenAIUrlReadVersionDeps(
        call_openai_url_file_read=None,
        call_openai_url_recovery=None,
        format_openai_url_read_document=lambda url, payload, text: f"{url}\n{payload['title']}\n{text}",
        get_minio_client=lambda: object(),
        upload_text=upload_text,
        ensure_source_version=ensure_version,
    )


@pytest.mark.asyncio
async def test_model_url_reader_cannot_promote_cookie_shell() -> None:
    source = Source(
        id=uuid.uuid4(),
        project_id=uuid.uuid4(),
        source_type=SourceType.WEB,
        original_url="https://example.com/article",
    )
    calls = {"versions": [], "uploads": []}
    result = {
        "read_status": "readable",
        "title": "Cookie settings",
        "canonical_url": source.original_url,
        "content_type": "text/html",
        "extracted_text_markdown": (
            "Manage your cookie preferences. Cookie settings. "
            "Accept only necessary cookies. Accept all cookies."
        ),
        "summary": "Cookie controls",
        "failure_reason": "",
        "confidence": 0.9,
    }

    versions = await _persist_openai_url_read_version(
        SimpleNamespace(),  # type: ignore[arg-type]
        source,
        result,
        _url_read_deps(calls),
    )

    assert versions == []
    assert calls == {"versions": [], "uploads": []}
    assert source.title is None
    assert source.metadata_["v2_openai_url_read"]["content_assessment"]["state"] == "unavailable"


@pytest.mark.asyncio
async def test_model_url_reader_promotes_confirmed_document() -> None:
    source = Source(
        id=uuid.uuid4(),
        project_id=uuid.uuid4(),
        source_type=SourceType.WEB,
        original_url="https://example.com/article",
    )
    calls = {"versions": [], "uploads": []}
    result = {
        "read_status": "readable",
        "title": "A substantive report",
        "canonical_url": source.original_url,
        "content_type": "text/markdown",
        "extracted_text_markdown": (
            "The report explains the history, operating mechanism, evidence, consequences, and limits. " * 20
        ),
        "summary": "A report",
        "failure_reason": "",
        "confidence": 0.9,
    }

    versions = await _persist_openai_url_read_version(
        SimpleNamespace(),  # type: ignore[arg-type]
        source,
        result,
        _url_read_deps(calls),
    )

    assert len(versions) == 1
    assert len(calls["uploads"]) == 1
    assert calls["versions"][0]["metadata"]["content_assessment"]["state"] == "confirmed"
    assert source.title == "A substantive report"
