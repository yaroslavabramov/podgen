def test_http_failure_with_substantive_document_body_is_confirmed_with_diagnostic() -> None:
    assessment = assess_web_source_content(
        "A long document body with detailed history, mechanisms, evidence, and consequences. " * 20,
        surface="rendered_snapshot",
        http_status=403,
        content_type="text/html",
    )

    assert assessment.state == CONTENT_STATE_CONFIRMED
    assert assessment.reasons == ("http_status_403",)


